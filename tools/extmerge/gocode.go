package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/hansjlachmann/goeasyerp/backend/foundation/apps"
)

// An app's Go code is a Go module in its directory (go.mod next to its application.yaml); the
// module's root package has
//
//	func Register()
//
// which registers the app's business logic (gtables.Register<Table>Logic …). With --go-root
// (the base repository being built) the merge links the apps' modules into the program:
//
//   - go.work joins the base module and each app's module, so an app compiles against the
//     merged definitions' generated tables;
//   - backend/installedapps/apps_gen.go installs each app — extensions.Install(id,
//     <pkg>.Register) — in dependency order, after the base application's logic (the package
//     imports it); the server and the tests import the package.

// baseModule is the base application's Go module
const baseModule = "github.com/hansjlachmann/goeasyerp"

// goApp is an app with Go code: its module directory and module path, and the base module
// version its go.mod requires (its own CI builds against that release)
type goApp struct {
	app         *apps.App
	dir         string
	module      string
	baseVersion string
}

// writeGoWiring writes go.work and backend/installedapps/apps_gen.go into the base repository for the
// apps that have Go code (nothing when none has)
func writeGoWiring(ordered []*apps.App, dirOf map[string]string, root string, verbose bool) error {
	var withCode []goApp
	for _, ext := range ordered {
		dir := dirOf[ext.ID]
		module, baseVersion, err := readGoMod(filepath.Join(dir, "go.mod"))
		if os.IsNotExist(err) {
			continue
		}
		if err != nil {
			return fmt.Errorf("%s: %w", ext.Name, err)
		}
		if baseVersion == "" {
			return fmt.Errorf("%s: its go.mod must require %s (the base it builds on)", ext.Name, baseModule)
		}
		abs, err := filepath.Abs(dir)
		if err != nil {
			return err
		}
		withCode = append(withCode, goApp{app: ext, dir: abs, module: module, baseVersion: baseVersion})
	}
	if len(withCode) == 0 {
		return nil
	}

	var work strings.Builder
	work.WriteString("// Written by extmerge: the base module and the extension apps' modules\ngo 1.26.0\n\nuse (\n\t.\n")
	for _, g := range withCode {
		fmt.Fprintf(&work, "\t%s\n", g.dir)
	}
	work.WriteString(")\n")
	// the base release an app requires is the base being built
	replaced := map[string]bool{}
	for _, g := range withCode {
		if !replaced[g.baseVersion] {
			replaced[g.baseVersion] = true
			fmt.Fprintf(&work, "\nreplace %s %s => ./\n", baseModule, g.baseVersion)
		}
	}
	err := os.WriteFile(filepath.Join(root, "go.work"), []byte(work.String()), 0644)
	if err != nil {
		return err
	}

	var gen strings.Builder
	gen.WriteString("// Code generated by extmerge. DO NOT EDIT.\n\npackage installedapps\n\nimport (\n")
	gen.WriteString("\t\"github.com/hansjlachmann/goeasyerp/backend/foundation/extensions\"\n")
	for _, g := range withCode {
		fmt.Fprintf(&gen, "\t%s %q\n", g.app.Prefix, g.module)
	}
	gen.WriteString(")\n\n// The extension apps' Go code, in dependency order (after the base application's logic)\nfunc init() {\n")
	for _, g := range withCode {
		fmt.Fprintf(&gen, "\textensions.Install(%q, %s.Register) // %s %s\n", g.app.ID, g.app.Prefix, g.app.Name, g.app.Version)
	}
	gen.WriteString("}\n")
	err = os.WriteFile(filepath.Join(root, "backend", "installedapps", "apps_gen.go"), []byte(gen.String()), 0644)
	if err != nil {
		return err
	}
	if verbose {
		fmt.Printf("Linked the Go code of %d app(s): go.work, backend/installedapps/apps_gen.go\n", len(withCode))
	}
	return nil
}

// readGoMod reads a go.mod's module path and the version it requires of the base module
func readGoMod(goMod string) (module, baseVersion string, err error) {
	f, err := os.Open(goMod)
	if err != nil {
		return "", "", err
	}
	defer func() { _ = f.Close() }()
	scanner := bufio.NewScanner(f)
	inRequire := false
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		line, _, _ = strings.Cut(line, "//")
		fields := strings.Fields(line)
		switch {
		case len(fields) == 0:
		case fields[0] == "module" && len(fields) == 2:
			module = strings.Trim(fields[1], `"`)
		case fields[0] == "require" && len(fields) == 2 && fields[1] == "(":
			inRequire = true
		case inRequire && fields[0] == ")":
			inRequire = false
		case fields[0] == "require" && len(fields) >= 3 && fields[1] == baseModule:
			baseVersion = fields[2]
		case inRequire && len(fields) >= 2 && fields[0] == baseModule:
			baseVersion = fields[1]
		}
	}
	if module == "" {
		return "", "", fmt.Errorf("%s has no module line", goMod)
	}
	return module, baseVersion, scanner.Err()
}
